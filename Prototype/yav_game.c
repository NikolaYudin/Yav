    /* stage 3: hand over the acorns here to finish task 2 (old saves compat) */
    if (g_quest == 3 && g_acorns >= 3) {
        g_quest = 4;
        SaveProfile();
    }
    ShowDialogTop(D_SMITH_GOLD);   /* already armed: hint */
    (void)hwnd;
