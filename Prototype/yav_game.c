/* Atomic save: write temp then MoveFileEx replace => never corrupts on crash */
static void SaveProfile(void)
{
    wchar_t wpath[MAX_PATH], wtmp[MAX_PATH];
    if (g_editNick && g_screen == SCR_SELECT)
        GetWindowTextW(g_editNick, g_nick, 63); /* keep live nickname */
    char apath[MAX_PATH*3], atmp[MAX_PATH*3], nutf[256];
    FILE* f;
    time_t t = time(NULL);
    struct tm tmv;
    char stamp[32];

    ProfilePathW(wpath, MAX_PATH);
    lstrcpynW(wtmp, wpath, MAX_PATH);
    wcscat(wtmp, L".tmp");

    WideCharToMultiByte(CP_UTF8, 0, wpath, -1, apath, sizeof(apath), NULL, NULL);
    WideCharToMultiByte(CP_UTF8, 0, wtmp,  -1, atmp,  sizeof(atmp),  NULL, NULL);
    WideCharToMultiByte(CP_UTF8, 0, g_nick, -1, nutf, sizeof(nutf), NULL, NULL);

#ifdef _MSC_VER
    localtime_s(&tmv, &t);
#else
    tmv = *localtime(&t);
#endif
    strftime(stamp, sizeof(stamp), "%Y-%m-%dT%H:%M:%S", &tmv);

    f = fopen(atmp, "w");
    if (!f) return;
    /* v0.4: inventory + equipment + quest progress serialized too */
    {
        char invJson[512]; int o = 0, i;
        o += snprintf(invJson + o, sizeof(invJson) - o, "[");
        for (i = 0; i < INV_CAP; i++)
            o += snprintf(invJson + o, sizeof(invJson) - o, "%s%d:%d",
                          i ? "," : "", g_inv[i].id, g_inv[i].count);
        snprintf(invJson + o, sizeof(invJson) - o, "]");
        fprintf(f,
            "{\n"
            "  \"version\": 4,\n"
            "  \"updatedAt\": \"%s\",\n"
            "  \"nickname\": \"%s\",\n"
            "  \"classId\": %d,\n"
            "  \"hp\": %d,\n"
            "  \"hpMax\": %d,\n"
            "  \"energy\": %d,\n"
            "  \"level\": %d,\n"
            "  \"profBonus\": %d,\n"
            "  \"youngster\": %d,\n"
            "  \"pos\": { \"x\": %d, \"y\": %d },\n"
            "  \"quest\": { \"step\": %d, \"q\": %d, \"acorns\": %d, \"catTalked\": %s, \"smith\": %d, \"marya\": %d },\n"
            "  \"equip\": { \"w\": %d, \"a\": %d, \"r\": %d },\n"
            "  \"inventory\": %s,\n"
            "  \"acornTaken\": [%d, %d, %d]\n"
            "}\n",
            stamp, nutf, g_selected, g_hpCur, g_hpMax, g_energyCur,
            g_level, g_profBonus, g_youngster, g_px, g_py,
            g_questStep, g_quest, g_acorns, g_catTalked ? "true" : "false",
            g_smithStage, g_maryaStage,
            g_equipW, g_equipA, g_equipR, invJson,
            g_acorns_arr[0].taken, g_acorns_arr[1].taken, g_acorns_arr[2].taken);
    }
    fclose(f);

    /* atomic replace: MoveFileEx(REPLACE_EXISTING) without prior delete */
    if (!MoveFileExA(atmp, apath, MOVEFILE_REPLACE_EXISTING | MOVEFILE_WRITE_THROUGH)) {
        remove(atmp);
        rename(atmp, apath);
    }
    g_lastSave = GetTickCount64();
    g_saveFlashUntil = g_lastSave + 1500;
}

/* Minimal JSON reader for our own format (tolerant of key order) */
static int JsonGetInt(const char* js, const char* key, int def)
{
    char pat[64];
    const char* p;
    snprintf(pat, sizeof(pat), "\"%s\"", key);
    p = strstr(js, pat);
    if (!p) return def;
    p += strlen(pat);
    p = strchr(p, ':');
    if (!p) return def;
    return atoi(p + 1);
}
static void JsonGetStr(const char* js, const char* key, wchar_t* out, size_t cch, const wchar_t* def)
{
    char pat[64], buf[256];
    const char* p, *s, *e;
    int n;
    snprintf(pat, sizeof(pat), "\"%s\"", key);
    p = strstr(js, pat);
    wcscpy(out, def);
    if (!p) return;
    p = strchr(p + strlen(pat), '"');
    if (!p) return;
    s = p + 1;
    e = strchr(s, '"');
    if (!e) return;
    n = (int)(e - s);
    if (n > 250) n = 250;
    memcpy(buf, s, n);
    buf[n] = 0;
    MultiByteToWideChar(CP_UTF8, 0, buf, -1, out, (int)cch);
}

static int LoadProfile(void) /* returns 1 if a valid profile was loaded */
{
    wchar_t wpath[MAX_PATH];
    char apath[MAX_PATH*3];
    FILE* f;
    long sz;
    char* buf;
    int ok = 0, i;

    ProfilePathW(wpath, MAX_PATH);
    WideCharToMultiByte(CP_UTF8, 0, wpath, -1, apath, sizeof(apath), NULL, NULL);
    f = fopen(apath, "rb");
    if (!f) return 0;
    fseek(f, 0, SEEK_END); sz = ftell(f); fseek(f, 0, SEEK_SET);
    if (sz <= 0 || sz > 65536) { fclose(f); return 0; }
    buf = (char*)malloc(sz + 1);
    if (!buf) { fclose(f); return 0; }
    if (fread(buf, 1, sz, f) != (size_t)sz) { free(buf); fclose(f); return 0; }
    buf[sz] = 0;
    fclose(f);

    if (strstr(buf, "\"classId\"")) {
        g_selected   = JsonGetInt(buf, "classId", -1);
        g_hpMax      = JsonGetInt(buf, "hpMax", g_class[g_selected >= 0 && g_selected < NCLASS ? g_selected : 0].hp);
        g_hpCur      = JsonGetInt(buf, "hp", g_hpMax);
        g_energyMax  = (g_selected >= 0 && g_selected < NCLASS) ? g_class[g_selected].energy : 60;
        g_energyCur  = JsonGetInt(buf, "energy", g_energyMax);
        if (g_energyCur > g_energyMax) g_energyCur = g_energyMax;
        g_level      = JsonGetInt(buf, "level", 1);
        g_profBonus  = JsonGetInt(buf, "profBonus", 0);
        g_youngster  = JsonGetInt(buf, "youngster", 1);
        g_px         = JsonGetInt(buf, "x", 320);
        g_py         = JsonGetInt(buf, "y", 380);
        g_questStep  = JsonGetInt(buf, "step", 0);
        g_quest      = JsonGetInt(buf, "q", 0);
        g_acorns     = JsonGetInt(buf, "acorns", 0);
        g_smithStage = JsonGetInt(buf, "smith", 0);
        g_maryaStage = JsonGetInt(buf, "marya", 0);
        g_catTalked  = strstr(buf, "\"catTalked\": true") ? 1 : 0;
        for (i = 0; i < 3; i++) g_acorns_arr[i].taken = (i < g_acorns) ? 1 : 0;
        /* equipment */
        g_equipW = JsonGetInt(buf, "w", 0);
        g_equipA = JsonGetInt(buf, "a", 0);
        g_equipR = JsonGetInt(buf, "r", 0);
        /* inventory: "inventory": [id:count,...] — tolerant manual parse */
        memset(g_inv, 0, sizeof(g_inv));
        { const char* p = strstr(buf, "\"inventory\"");
          if (p) {
            int slot = 0;
            p = strchr(p, '[');
            if (p) {
                p++;
                while (*p && *p != ']' && slot < INV_CAP) {
                    int id = (int)strtol(p, (char**)&p, 10), cnt = 0;
                    if (*p == ':') { cnt = (int)strtol(p + 1, (char**)&p, 10); }
                    if (id > 0) { g_inv[slot].id = id; g_inv[slot].count = cnt; slot++; }
                    while (*p == ',' || *p == ' ' || *p == '\n') p++;
                    if (!isdigit((unsigned char)*p) && *p != '-') break;
                }
            }
          } }
        JsonGetStr(buf, "nickname", g_nick, 64, L"");
        if (g_selected >= 0 && g_selected < NCLASS && wcslen(g_nick) > 0) ok = 1;
    }
    free(buf);
    return ok;
}

