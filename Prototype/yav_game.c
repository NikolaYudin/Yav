static void TryPickAcorn(HWND hwnd)
{
    int i, best = -1; double bd = 1e9;
    for (i = 0; i < 3; i++) {
        int dx, dy; double d;
        if (g_acorns_arr[i].taken) continue;
        dx = g_px - g_acorns_arr[i].x; dy = g_py - g_acorns_arr[i].y;
        d = sqrt((double)(dx*dx + dy*dy));
        if (d < PICK_R && d < bd) { bd = d; best = i; }
    }
    if (best < 0) return;
    g_acorns_arr[best].taken = 1;
    g_acorns++;
    InvAdd(ITEM_ACORN, 1);
    if (g_quest == 2 && g_acorns >= 3) { g_quest = 3; QuestAdvanceCheck(); }
    SaveProfile();               /* real-time autosave on loot */
    InvalidateRect(hwnd, NULL, FALSE);
}

static void TalkCat(HWND hwnd)
{
    if (g_dialogShown) { g_dialogShown = 0; InvalidateRect(hwnd, NULL, FALSE); return; }
    /* step machine:
       0 not greeted -> greet, start task1
       1 greeted     -> give acorn task + starter items (metal/cloth/potion)
       2 acorns pending
       3 smith pending
       4 marya pending
       5 all done -> profession choice screen
       6 hero (profession chosen) */
    switch (g_quest) {
        case 0: {
            wchar_t greet[320];
            swprintf(greet, 320, D_CAT_NEW, g_nick[0] ? g_nick : L"???");
            ShowDialogTop(greet);
            g_catTalked = 1;
            g_quest = 1;
            SaveProfile();
            return; }
        case 1:
            ShowDialogTop(D_CAT_Q1);
            /* starter kit: metal for smith, cloth for marya, potion */
            InvAdd(ITEM_METAL, 1); InvAdd(ITEM_CLOTH, 1); InvAdd(ITEM_POTION, 2);
            g_quest = 2;
            SaveProfile();
            return;
        case 2:
            if (g_acorns >= 3) {
                InvAdd(ITEM_ACORN, 0);
                ShowDialogTop(D_CAT_Q2);
                g_quest = 3;
            } else {
                wchar_t b[128];
                swprintf(b, 128, D_CAT_PROGRESS, g_acorns);
                ShowDialogTop(b);
            }
            SaveProfile();
            return;
        case 3:
            ShowDialogTop(g_smithStage >= 3 ? D_CAT_Q3 : D_CAT_NEED2);
            if (g_smithStage >= 3) g_quest = 4;
            SaveProfile();
            return;
        case 4:
            ShowDialogTop(g_maryaStage >= 3 ? D_CAT_FINAL : D_CAT_NEED3);
            if (g_maryaStage >= 3) g_quest = 5;
            SaveProfile();
            return;
        case 5:
            ShowDialogTop(D_CAT_FINAL);
            g_screen = SCR_PROF;           /* open profession choice overlay */
            LayoutForScreen(hwnd);
            return;
        default:
            ShowDialogTop(D_CAT_AGAIN);
            return;
    }
}

static void QuestAdvanceCheck(void)
{
    /* called when any task completes; if all 3 done -> go back to the cat */
    if (g_quest == 5) return;
}

