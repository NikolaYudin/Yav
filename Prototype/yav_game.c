/* 3D-ish horizontal bar: dark trough + colored fill + light top edge */
static void Bar3D(HDC hdc, int x, int y, int w, int h, double frac, COLORREF col)
{
    RECT tr = { x, y, x + w, y + h };
    HBRUSH b;
    if (frac < 0) frac = 0; if (frac > 1) frac = 1;
    b = CreateSolidBrush(RGB(0x0A,0x0C,0x14));
    FillRect(hdc, &tr, b); DeleteObject(b);
    { RECT fr = tr; fr.right = x + (int)(w * frac);
      b = CreateSolidBrush(col);
      FillRect(hdc, &fr, b); DeleteObject(b);
      /* glossy top half */
      { RECT gl = fr; gl.bottom = y + h/2;
        b = CreateSolidBrush(RGB(
            min(255, (int)GetRValue(col)+40),
            min(255, (int)GetGValue(col)+40),
            min(255, (int)GetBValue(col)+40)));
        FillRect(hdc, &gl, b); DeleteObject(b); } }
    DrawFrameAt(hdc, tr, RGB(0x55,0x5A,0x6A));
}

