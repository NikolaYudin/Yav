static void OnPaint(HWND hwnd)
{
    PAINTSTRUCT ps;
    HDC hdc = BeginPaint(hwnd, &ps);
    /* double buffer */
    HDC mem = CreateCompatibleDC(hdc);
    HBITMAP bmp = CreateCompatibleBitmap(hdc, WIN_W, WIN_H);
    HBITMAP old = (HBITMAP)SelectObject(mem, bmp);

    switch (g_screen) {
        case SCR_LAUNCH:   PaintLaunch(hwnd, mem);  break;
        case SCR_SELECT:   PaintSelect(hwnd, mem);  break;
        case SCR_LORE:
            RectFill(mem, 0, 0, WIN_W, WIN_H, RGB(0x0C,0x10,0x1A));
            TextC(mem, WIN_W/2, 40, L"\x041f\x0440\x0435\x0434\x0430\x043d\x0438\x0435", RGB(0xE8,0xC8,0x5A), g_fMed, 1);
            TextC(mem, 60, 90, LORE_TEXT, RGB(0xC8,0xC8,0xD8), g_fSmall, 0);
            break;
        case SCR_CONTINUE: PaintContinue(hwnd, mem); break;
        case SCR_WORLD:    PaintWorld(mem);          break;
        case SCR_PROF:     PaintProfession(hwnd, mem); break;
    }
    BitBlt(hdc, 0, 0, WIN_W, WIN_H, mem, 0, 0, SRCCOPY);
    SelectObject(mem, old);
    DeleteObject(bmp);
    DeleteDC(mem);
    EndPaint(hwnd, &ps);
}

