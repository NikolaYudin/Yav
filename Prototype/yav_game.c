static void EnterWorld(HWND hwnd)
{
    InitItems();
    BuildAbilities(); /* class-dependent hotbar */
    RespawnAcorns();  /* v0.6: oak never looks empty after a hand-over */
    /* v0.8 migration: profiles saved by the buggy v0.7 build could hold a
       half-started quest (task given but no acorns/resources in the bag).
       Re-sync the world to the quest state so nothing can deadlock. */
    if (g_quest >= 1 && g_quest <= 4) {
        if (g_acorns < 3 && !InvCount(ITEM_ACORN)) { /* fresh task: acorns already respawned above */ }
        if (g_quest >= 3 && !InvCount(ITEM_METAL)) InvAdd(ITEM_METAL, 1);
        if (g_quest >= 4 && !InvCount(ITEM_CLOTH)) InvAdd(ITEM_CLOTH, 1);
    }
    g_screen = SCR_WORLD;
    NetInit(hwnd);                 /* v0.19: LAN co-op (UDP broadcast) */
    SetTimer(hwnd, 2, 50, NULL);   /* mouse-walk / regen tick */
    LayoutForScreen(hwnd);
    SetFocus(hwnd);
    /* BUGFIX v0.8: the acorn task now starts IMMEDIATELY on entering the
       world — previously the hero spawned with an empty oak and had to talk
       to the cat twice (greet + task) before any acorns appeared. */
    if (g_quest == 0) {
        /* v0.16 FIX #3: D_CAT_NEW contains a %ls placeholder, so it MUST be
           pre-formatted with SafeWfmtN() — the old code copied the template
           verbatim into the dialog buffer and the hotbar/dialog painter read
           past the end of the static string pool => 0xC0000005 right after
           entering the world (the crash reported for v0.12..v0.14). */
        wchar_t greet[320];
        SafeWfmtN(greet, 320, D_CAT_NEW, g_nick[0] ? g_nick : L"???", 0, 1);
        ShowDialogTop(greet);
        g_catTalked = 1;
        g_quest = 1;
    }
    if (g_quest == 1) {
        ShowDialogTop(D_CAT_Q1);          /* "collect 3 acorns under the oak" */
        InvAdd(ITEM_POTION, 2);
        g_quest = 2;
        RespawnAcorns();                  /* acorns lie under the oak right now */
    }
    SaveProfile(); /* real-time: entering the world is persisted instantly */
}

static void TryPickAcorn(HWND hwnd)
{
    int i, best = -1; double bd = 1e9;
    for (i = 0; i < 3; i++) {
        int dx, dy; double d;
        if (g_acorns_arr[i].taken) continue;
        dx = g_px - g_acorns_arr[i].x; dy = g_py - g_acorns_arr[i].y;
        d = sqrt((double)(dx*dx + dy*dy));
        if (d < PICK_R && d < bd) { bd = d; best = i; }
    }
    if (best < 0) return;
    g_acorns_arr[best].taken = 1;
    g_acorns++;
    InvAdd(ITEM_ACORN, 1);
    /* BUGFIX v0.9: the acorn task used to jump straight to "report to cat"
       without any feedback — now every acorn shows a counter and finishing
       all three fires the completion toast immediately. */
    if (g_quest == 2 && g_acorns >= 3) {
        Toast(TST_Q1_DONE);
        QuestAdvanceCheck();
    } else if (g_quest == 2) {
        wchar_t b[64];
        SafeWfmt(b, 64, L"\x27E5 \u0416\u0435\u043b\u0443\u0434\u044c: %d/3", g_acorns);
        Toast(b);
    }
    SaveProfile();               /* real-time autosave on loot */
    InvalidateRect(hwnd, NULL, FALSE);
}

/* v0.6: hotbar "Сбор" button — pick up the nearest resource around the hero
   (acorns under the oak, or a metal shard / cloth scrap at the dark grove). */
static void PickNearbyResource(HWND hwnd)
{
    int i, best = -1; double bd = 1e9;
    /* acorns first */
    for (i = 0; i < 3; i++) {
        double dx = (double)(g_px - g_acorns_arr[i].x), dy = (double)(g_py - g_acorns_arr[i].y);
        double d = sqrt(dx*dx + dy*dy);
        if (!g_acorns_arr[i].taken && d < PICK_R + 44 && d < bd) { bd = d; best = i; }
    }
    if (best >= 0) { TryPickAcorn(hwnd); return; }
    /* grove spot: metal & cloth loot */
    {
        double dx = (double)(g_px - SPOT_X), dy = (double)(g_py - SPOT_Y);
        if (sqrt(dx*dx + dy*dy) < 52) {
            if (InvCount(ITEM_METAL) == 0)      { InvAdd(ITEM_METAL, 1); }
            else if (InvCount(ITEM_CLOTH) == 0) { InvAdd(ITEM_CLOTH, 1); }
            else                                { ShowDialogTop(D_PICKED_NONE); SaveProfile(); InvalidateRect(hwnd, NULL, FALSE); return; }
            SaveProfile();
            InvalidateRect(hwnd, NULL, FALSE);
            return;
        }
    }
    ShowDialogTop(D_PICKED_NONE);
    InvalidateRect(hwnd, NULL, FALSE);
}

/* v0.6: acorns respawn under the oak after they've all been handed over
   (or after an old save wiped them) so the world never looks empty. */
static void RespawnAcorns(void)
{
    int i, allTaken = 1;
    for (i = 0; i < 3; i++) if (!g_acorns_arr[i].taken) { allTaken = 0; break; }
    if (allTaken) memset(g_acorns_arr, 0, sizeof(g_acorns_arr));
}

