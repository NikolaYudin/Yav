static void TryPickAcorn(HWND hwnd)
{
    int i, best = -1; double bd = 1e9;
    for (i = 0; i < 3; i++) {
        int dx, dy; double d;
        if (g_acorns_arr[i].taken) continue;
        dx = g_px - g_acorns_arr[i].x; dy = g_py - g_acorns_arr[i].y;
        d = sqrt((double)(dx*dx + dy*dy));
        if (d < PICK_R && d < bd) { bd = d; best = i; }
    }
    if (best < 0) return;
    g_acorns_arr[best].taken = 1;
    g_acorns++;
    InvAdd(ITEM_ACORN, 1);
    AddXp(10);  /* v0.28: +10 XP per acorn — 3 tasks bring the hero to ~LVL 4.5 */
    /* BUGFIX v0.9: the acorn task used to jump straight to "report to cat"
       without any feedback — now every acorn shows a counter and finishing
       all three fires the completion toast immediately. */
    if (g_quest == 2 && g_acorns >= 3) {
        QuestCompleteToast(1, 15, TST_Q1_DONE);   /* v0.23: banner + reward */
        QuestAdvanceCheck();
    } else if (g_quest == 2) {
        wchar_t b[64];
        SafeWfmt(b, 64, L"\x27E5 \u0416\u0435\u043b\u0443\u0434\u044c: %d/3", g_acorns);
        Toast(b);
    }
    SaveProfile();               /* real-time autosave on loot */
    InvalidateRect(hwnd, NULL, FALSE);
}

/* v0.6: hotbar "Сбор" button — pick up the nearest resource around the hero
   (acorns under the oak, or a metal shard / cloth scrap at the dark grove). */
static void PickNearbyResource(HWND hwnd)
{
    int i, best = -1; double bd = 1e9;
    /* acorns first */
    for (i = 0; i < 3; i++) {
        double dx = (double)(g_px - g_acorns_arr[i].x), dy = (double)(g_py - g_acorns_arr[i].y);
        double d = sqrt(dx*dx + dy*dy);
        if (!g_acorns_arr[i].taken && d < PICK_R + 44 && d < bd) { bd = d; best = i; }
    }
    if (best >= 0) { TryPickAcorn(hwnd); return; }
    /* grove spot: metal & cloth loot */
    {
        double dx = (double)(g_px - SPOT_X), dy = (double)(g_py - SPOT_Y);
        if (sqrt(dx*dx + dy*dy) < 52) {
            if (InvCount(ITEM_METAL) == 0)      { InvAdd(ITEM_METAL, 1); }
            else if (InvCount(ITEM_CLOTH) == 0) { InvAdd(ITEM_CLOTH, 1); }
            else                                { ShowDialogTop(D_PICKED_NONE); SaveProfile(); InvalidateRect(hwnd, NULL, FALSE); return; }
            SaveProfile();
            InvalidateRect(hwnd, NULL, FALSE);
            return;
        }
    }
    ShowDialogTop(D_PICKED_NONE);
    InvalidateRect(hwnd, NULL, FALSE);
}

static int CountTakenAcorns(void)
{
    int i, n = 0;
    for (i = 0; i < 3; i++) if (g_acorns_arr[i].taken) n++;
    return n;
}

/* v0.6: acorns respawn under the oak after they've all been handed over
   (or after an old save wiped them) so the world never looks empty. */
static void RespawnAcorns(void)
{
    int i, allTaken = 1;
    for (i = 0; i < 3; i++) if (!g_acorns_arr[i].taken) { allTaken = 0; break; }
    /* BUGFIX v0.22: "all taken" used to mean only "all three collected".
       When two windows shared one profile file, window #2 saved its own
       acorn flags on top of window #1's and the second hero saw a fully
       picked oak (three stale taken-flags from the other player). Now we
       also respawn when fewer acorns are flagged taken than the bag holds
       already — physically impossible for one hero, so it can only mean
       foreign state. The oak restocks => both players always find their
       own acorns right after taking the cat's task. */
    if (allTaken || (g_quest == 2 && g_acorns != CountTakenAcorns())
        /* v0.25 FIX: the acorn counter can also lag behind the bag itself —
           e.g. a freshly greeted hero whose first SaveProfile raced with the
           second client, or a profile written before "acornTaken" existed.
           Any mismatch between flags and the actual bag means foreign or
           stale state => restock the oak so acorns appear right after the
           cat's task WITHOUT restarting the game. */
        || (g_quest == 2 && InvCount(ITEM_ACORN) > CountTakenAcorns()))
        memset(g_acorns_arr, 0, sizeof(g_acorns_arr));
    /* v0.25: while the acorn task is active the oak must ALWAYS show its
       three acorns unless this very hero already picked them (bag count). */
    if (g_quest == 2) {
        int have = InvCount(ITEM_ACORN);
        for (i = 0; i < 3; i++)
            if (g_acorns_arr[i].taken && i >= have) g_acorns_arr[i].taken = 0;
    }
}

