static void PaintWorld(HDC hdc)
{
    HPEN pen; HBRUSH br; RECT r; int i;
    wchar_t b[160];
    /* v0.17: camera follows the hero across the big world (2048x1536).
       Village lives at world offset OFF_X/OFF_Y; everything below is drawn
       in village-local coords inside CamBegin/CamEnd, which translate by
       (-camX,-camY) and clip to the view area under the HUD strip. */
    {
        int cx = g_px - WIN_W / 2;
        int cy = g_py - (VIEW_TOP + (WIN_H - VIEW_TOP) / 2);
        if (cx < 0) cx = 0; if (cx > WORLD_W - WIN_W) cx = WORLD_W - WIN_W;
        if (cy < 0) cy = 0; if (cy > WORLD_H - WIN_H) cy = WORLD_H - WIN_H;
        g_camX = cx; g_camY = cy;
    }
    /* sky + ground (window-space backdrop) */
    RectFill(hdc, 0, 0, WIN_W, WIN_H, RGB(0x14,0x18,0x26));
    RectFill(hdc, 0, WORLD_TOP, WIN_W, WIN_H - WORLD_TOP, RGB(0x1B,0x2A,0x1E));

    CamBegin(hdc);   /* ---- everything between here is WORLD space ---- */

    /* surroundings beyond the village: darker wilder grass + scattered pines */
    {
        int wx, wy;
        RectFill(hdc, -OFF_X, VIEW_TOP - OFF_Y, WORLD_W, WORLD_H, RGB(0x16,0x24,0x19));
        for (wy = 0; wy < WORLD_H; wy += 192)
            for (wx = 0; wx < WORLD_W; wx += 192) {
                /* pseudo-random tree placement, skip the village footprint */
                int sx = wx + ((wx*7 + wy*13) % 120), sy = wy + ((wx*11 + wy*5) % 120);
                if (sx > OFF_X - 40 && sx < OFF_X + WIN_W + 40 &&
                    sy > OFF_Y - 40 && sy < OFF_Y + WIN_H + 40) continue;
                if ((sx*3 + sy*7) % 5 != 0) continue;      /* sparse forest */
                br = CreateSolidBrush(RGB(0x2F,0x4A,0x30));
                { RECT tri = { sx - 10, sy + 6, sx + 10, sy + 6 }; (void)tri; }
                DeleteObject(br);
                FillEllipse(hdc, sx, sy, 12, 18, RGB(0x24,0x40,0x26));   /* pine crown */
                br = CreateSolidBrush(RGB(0x4A,0x34,0x20));
                { RECT tk = { sx - 2, sy + 14, sx + 2, sy + 22 }; FillRect(hdc, &tk, br); }
                DeleteObject(br);
            }
    }
    /* v0.18 FIX: village floor patch — a full window-sized yard starting at
       the top HUD line (OFF_Y), NOT collapsed to a thin strip like before. */
    RectFill(hdc, OFF_X, OFF_Y, WIN_W, WIN_H, RGB(0x1B,0x2A,0x1E));
    /* fence palisade around the village footprint (world coords) */
    { HPEN fp = CreatePen(PS_SOLID, 2, RGB(0x6A,0x5A,0x3A));
      HPEN fo = (HPEN)SelectObject(hdc, fp);
      SelectObject(hdc, GetStockObject(NULL_BRUSH));
      Rectangle(hdc, OFF_X + 14, OFF_Y + WORLD_TOP, OFF_X + WIN_W - 14, OFF_Y + WIN_H - 40);
      SelectObject(hdc, fo); DeleteObject(fp); }
    /* road across the village */
    RectFill(hdc, OFF_X, OFF_Y + 300, WIN_W, 60, RGB(0x3A,0x34,0x2A));
    /* v0.19: huts are drawn at their TRUE world positions (SMITH_X/SMITH_Y),
       so the picture and the collision boxes always match — previously the
       hut was painted at one place and blocked you somewhere else. */
    for (i = 0; i < 2; i++) {
        int cxw = (i == 0 ? SMITH_X : MARYA_X);   /* hut centre x (world) */
        int cyw = (i == 0 ? SMITH_Y : MARYA_Y);   /* door line y  (world) */
        RECT hr = { cxw - 66, cyw - 88, cxw + 66, cyw };
        br = CreateSolidBrush(RGB(0x6A,0x4A,0x2A));
        FillRect(hdc, &hr, br); DeleteObject(br);
        pen = CreatePen(PS_SOLID, 2, RGB(0x3A,0x2A,0x1A));
        { HPEN o = (HPEN)SelectObject(hdc, pen);
          SelectObject(hdc, GetStockObject(NULL_BRUSH));
          Rectangle(hdc, hr.left, hr.top, hr.right, hr.bottom);
          MoveToEx(hdc, hr.left, hr.top, NULL); LineTo(hdc, (hr.left+hr.right)/2, hr.top - 24);
          LineTo(hdc, hr.right, hr.top);
          SelectObject(hdc, o); }
        DeleteObject(pen);
        br = CreateSolidBrush(RGB(0x2A,0x22,0x14));
        { RECT door = { (hr.left+hr.right)/2 - 10, hr.bottom - 40, (hr.left+hr.right)/2 + 10, hr.bottom };
          FillRect(hdc, &door, br); }
        DeleteObject(br);
        TextC(hdc, (hr.left+hr.right)/2, hr.bottom + 4,
              i == 0 ? NPC_SMITH : NPC_MARYA, RGB(0xC8,0xC8,0xD8), g_fSmall, 1);
    }
    /* oak (OAK_X/OAK_Y are WORLD coords — no extra OFF_* offset) */
    br = CreateSolidBrush(RGB(0x5A,0x3A,0x20));
    { RECT trunk = { OAK_X - 12, OAK_Y + 10, OAK_X + 12, OAK_Y + 60 }; FillRect(hdc, &trunk, br); }
    DeleteObject(br);
    FillEllipse(hdc, OAK_X, OAK_Y - 14, 52, 38, RGB(0x2A,0x5A,0x2A));
    TextC(hdc, OAK_X, OAK_Y + 62, T_OAK, RGB(0xC8,0xC8,0xD8), g_fSmall, 1);
    /* dark grove spot (v0.7: shows remaining loot) */
    PaintGroveSpot(hdc);
    /* v0.17/v0.20 FIX: movement grid. We are INSIDE CamBegin here, so all
       coordinates must be WORLD coords. The old code passed VIEW_TOP/WIN_H
       (screen values) as world y — the horizontal lines landed ~672 px above
       the visible area ("карта обрезана, сетка не совпадает"). Now the grid
       spans exactly the visible world rect [cam .. cam+WIN] x [VIEW_TOP+camY ..]. */
    if (g_screen == SCR_WORLD) {
        int wx0 = ((g_camX) / 32) * 32, wy0 = ((g_camY + VIEW_TOP) / 32) * 32;
        int wx1 = g_camX + WIN_W, wy1 = g_camY + WIN_H;
        HPEN gp = CreatePen(PS_DOT, 1, RGB(0x2E,0x4A,0x38));
        { HPEN o=(HPEN)SelectObject(hdc,gp); SelectObject(hdc,GetStockObject(NULL_BRUSH));
          for (i = wx0; i <= wx1; i += 32) { MoveToEx(hdc,i,g_camY + VIEW_TOP,NULL); LineTo(hdc,i,wy1); }
          for (i = wy0; i <= wy1; i += 32) { MoveToEx(hdc,wx0,i,NULL); LineTo(hdc,wx1,i); }
          SelectObject(hdc,o);} DeleteObject(gp);
    }
    /* v0.17: L-shaped trajectory preview — two straight legs with a corner */
    if (g_walkDestSet) {
        int wx = g_walkX, wy = g_walkY;      /* final target (world coords) */
        int cxx = wx, cyy = wy;              /* corner of the L */
        double adx = fabs((double)(wx - g_px)), ady = fabs((double)(wy - g_py));
        HPEN tp; POINT ar[3];
        COLORREF tc = RGB(0xFF,0xE9,0x7A);
        if (g_wpActive) { cxx = g_wpx; cyy = g_wpy; }   /* use the actual planned corner */
        else if (adx >= ady) cyy = g_py; else cxx = g_px;   /* dominant axis first */
        if (BlockedAt(wx, wy) || BlockedAt(cxx, cyy)) tc = RGB(0xC0,0x50,0x50);
        tp = CreatePen(PS_DASH, 2, tc);
        { HPEN o=(HPEN)SelectObject(hdc,tp);
          MoveToEx(hdc, g_px, g_py, NULL); LineTo(hdc, cxx, cyy);   /* leg 1 */
          LineTo(hdc, wx, wy);                                       /* leg 2 */
          SelectObject(hdc,o);} DeleteObject(tp);
        FillCircle(hdc, cxx, cyy, 3, tc);                           /* corner dot */
        FillCircle(hdc, wx, wy, 4, tc);
        ar[0].x = wx - 6; ar[0].y = wy - 6; ar[1].x = wx + 6; ar[1].y = wy - 6; ar[2].x = wx; ar[2].y = wy + 7;
        { HBRUSH fb = CreateSolidBrush(tc);
          HPEN o=(HPEN)SelectObject(hdc,GetStockObject(NULL_PEN));
          Polygon(hdc, ar, 3); SelectObject(hdc,o); DeleteObject(fb);}
    }
    /* acorns: small nut with cap (matches the IT_ACORN icon color) */
    for (i = 0; i < 3; i++) {
        if (g_acorns_arr[i].taken) continue;
        FillCircle(hdc, g_acorns_arr[i].x, g_acorns_arr[i].y, 6, RGB(0xC8,0x8A,0x3E));
        FillEllipse(hdc, g_acorns_arr[i].x, g_acorns_arr[i].y - 5, 7, 4, RGB(0x6B,0x4A,0x24));
    }
    /* cat body + spectacles + scroll (Kot Ucheny) */
    DrawVillageCatParts(hdc);
    /* hero: head, class-colored body, nickname below (camera-offset inside) */
    DrawHero(hdc);
    /* focus ring around focused entity (v0.19: CAT_X/SMITH_X are ALREADY world
       coords — the extra +OFF_* here doubled the offset and drew the ring on
       top of a pine tree far from the NPC, part of "объекты разбежались") */
    if (g_focusKind == 1) {
        /* v0.20: raw GDI Ellipse here used the OLD bounding-box convention;
           our FillEllipse helper uses centre+radius like everything else. */
        int fx = (g_focusId == 0 ? CAT_X : g_focusId == 1 ? SMITH_X : MARYA_X);
        int fy = (g_focusId == 0 ? CAT_Y : g_focusId == 1 ? SMITH_Y + 30 : MARYA_Y + 30);
        HPEN fp = CreatePen(PS_SOLID, 2, RGB(0xFF,0xE9,0x7A));
        HPEN fo = (HPEN)SelectObject(hdc, fp);
        HBRUSH fb = (HBRUSH)SelectObject(hdc, GetStockObject(NULL_BRUSH));
        Ellipse(hdc, fx - 26, fy - 24, fx + 26, fy + 24);
        SelectObject(hdc, fo); SelectObject(hdc, fb); DeleteObject(fp);
    }
    /* v0.19: the old "hint above player" block drew its text in WORLD coords
       while the camera transform was already reset — with a panned camera the
       hint appeared hundreds of px away from the hero (part of the "карта
       разбежалась" complaint). It is now drawn AFTER CamEnd in screen space. */
    CamEnd(hdc);   /* ---------------- back to window space ---------------- */

    UpdateFocus();
    if (g_focusKind) {
        const wchar_t* hint = HINT_TALK;
        int hsx = g_px - g_camX, hsy = g_py - g_camY - 34;
        if (g_focusKind == 2) hint = HINT_PICK;
        else if (g_focusKind == 3) hint = (g_focusId == 0) ? HINT_PICK : HINT_LEAVE;
        else if (g_focusKind == 1) {
            if (g_focusId == 1) {
                if (g_smithStage == 0) hint = (InvCount(ITEM_METAL) > 0 && g_quest >= 2) ? HINT_HAND : HINT_FORGE;
                else if (g_smithStage == 2) hint = HINT_WAIT;
                else hint = HINT_DONE;
            } else if (g_focusId == 2) {
                if (g_maryaStage == 0) hint = (InvCount(ITEM_CLOTH) > 0 && g_quest >= 2) ? HINT_HAND : HINT_WEAVE;
                else if (g_maryaStage == 2) hint = HINT_WAIT;
                else hint = HINT_DONE;
            }
        }
        TextC(hdc, hsx, hsy, hint, RGB(0xFF,0xE9,0x7A), g_fSmall, 1);
    }
    /* v0.19: LAN peers (other players) — drawn in screen space after CamEnd */
    NetDrawPeers(hdc);
    /* HUD layers */
    PaintPlayerPanel(hdc);
    PaintMinimap(hdc);      /* v0.18: big-world minimap, top-right corner */
    PaintFocusInfo(hdc);
    PaintAbilityBar(hdc);
    PaintInventory(hdc);
    PaintDialogBox(hdc);
    PaintToast(hdc);
    PaintInvTooltip(hdc);   /* v0.16: item hint on hover (drawn last, above all) */
    /* quest tracker under focus info */
    {
        const wchar_t* qtxt;
        switch (g_quest) {
            case 0: qtxt = Q_NONE; break;
            case 1: qtxt = Q_GREET; break;
            case 2: qtxt = Q1; break;
            case 3: qtxt = Q2; break;
            case 4: qtxt = Q3; break;
            case 5: qtxt = Q_PROF; break;
            default: qtxt = Q_FIN; break;
        }
        SafeWfmt(b, 160, L"%ls %ls", Q_TITLE, qtxt);
        TextC(hdc, WIN_W/2, 46, b, RGB(0x9A,0xE0,0x9A), g_fSmall, 1);
    }
    /* bottom hint */
    TextC(hdc, WIN_W/2, WIN_H - 20, W_HINT, RGB(0x7A,0x86,0x9A), g_fSmall, 1);
    (void)r;
}

