static void DrawCard(LPDRAWITEMSTRUCT dis, int idx)
{
    HDC hdc = dis->hDC; RECT rc = dis->rcItem;
    BOOL sel = (g_selected == idx);
    BOOL hot = (dis->itemState & (ODS_HOTLIGHT|ODS_SELECTED)) != 0;
    HBRUSH b = CreateSolidBrush(sel ? g_class[idx].color : (hot ? RGB(58,66,96) : RGB(24,28,46)));
    FillRect(hdc, &rc, b); DeleteObject(b);
    DrawFrame(hdc, rc, sel ? RGB(240,220,160) : RGB(72,76,100), sel ? 3 : 1);
    SetBkMode(hdc, TRANSPARENT);
    CenterText(hdc, g_class[idx].name, (rc.left+rc.right)/2, rc.top+12, RGB(240,238,245), g_fBig);
    CenterText(hdc, g_class[idx].tag,   (rc.left+rc.right)/2, rc.top+46, RGB(180,180,195), g_fSmall);
    {
        RECT dr = { rc.left+12, rc.top+74, rc.right-12, rc.bottom-34 };
        SetTextColor(hdc, RGB(208,208,220)); SelectObject(hdc, g_fSmall);
        DrawTextW(hdc, g_class[idx].desc, -1, &dr, DT_WORDBREAK|DT_LEFT);
    }
    {
        wchar_t st[96];
        wsprintfW(st, L"HP %d  \x2022  DMG %d  \x2022  MANA %d  \x2022  LOOT +%d",
                  g_class[idx].hp, g_class[idx].dmg, g_class[idx].energy, g_class[idx].carry);
        CenterText(hdc, st, (rc.left+rc.right)/2, rc.bottom-28, RGB(160,205,160), g_fSmall);
    }
}

static void DrawLabelButton(LPDRAWITEMSTRUCT dis, const wchar_t* label, COLORREF base)
{
    HDC hdc = dis->hDC; RECT rc = dis->rcItem;
    BOOL hot = (dis->itemState & (ODS_HOTLIGHT|ODS_SELECTED)) != 0;
    HBRUSH b = CreateSolidBrush(hot ? RGB(96,74,42) : base);
    FillRect(hdc, &rc, b); DeleteObject(b);
    DrawFrame(hdc, rc, RGB(130,130,160), 1);
    SetBkMode(hdc, TRANSPARENT);
    {
        SIZE sz; SetTextColor(hdc, RGB(238,238,242)); SelectObject(hdc, g_fMed);
        GetTextExtentPoint32W(hdc, label, (int)wcslen(label), &sz);
        TextOutW(hdc, rc.left+(rc.right-rc.left)/2 - sz.cx/2,
                     rc.top +(rc.bottom-rc.top )/2 - sz.cy/2, label, (int)wcslen(label));
    }
}

