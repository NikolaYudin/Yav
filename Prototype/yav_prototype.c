{
    switch (dis->CtlID) {
    case IDC_BTN_START:  DrawLabelButton(dis, B_START, RGB(44,52,78));  break;
    case IDC_BTN_LORE:   DrawLabelButton(dis, B_LORE,  RGB(44,52,78));  break;
    case IDC_BTN_QUIT:   DrawLabelButton(dis, B_EXIT,  RGB(64,36,40));  break;
    case IDC_BTN_BACK:   DrawLabelButton(dis, B_BACK,  RGB(44,52,78));  break;
    case IDC_BTN_OK:     DrawLabelButton(dis, B_OK,    RGB(44,52,78));  break;
    case IDC_BTN_CHOOSE: DrawLabelButton(dis, g_selected>=0 ? B_CHOOSE : B_NEED, RGB(52,60,44)); break;
    case IDC_CARD_0: case IDC_CARD_1: case IDC_CARD_2:
        DrawCard(dis, dis->CtlID - IDC_CARD_0); break;
    }
}

