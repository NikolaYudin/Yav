/* ---------- File DB: dump of the choice to JSON next to the exe ---------- */
static void SaveProfile(void)
{
    wchar_t wpath[MAX_PATH], nick[64] = L"";
    char apath[MAX_PATH * 3], nutf[256] = "hero";
    FILE* f;
    wchar_t* dot;

    GetModuleFileNameW(NULL, wpath, MAX_PATH);
    dot = wcsrchr(wpath, L'.');
    if (dot) wcscpy(dot, L"_profile.json");
    WideCharToMultiByte(CP_UTF8, 0, wpath, -1, apath, sizeof(apath), NULL, NULL);

    if (g_editNick) GetWindowTextW(g_editNick, nick, 63);
    WideCharToMultiByte(CP_UTF8, 0, nick, -1, nutf, sizeof(nutf), NULL, NULL);

    f = fopen(apath, "w");
    if (!f) return;
    fprintf(f, "{\n  \"nickname\": \"%s\",\n  \"classId\": %d,\n  \"classRu\": \"%ls\"\n}\n",
            nutf, g_selected, g_selected >= 0 ? g_class[g_selected].name : L"?");
    fclose(f);
}

/* ------------------------------ Rendering -------------------------------- */
/* Simple frame: 4 lines (FrameRect expects a BRUSH, not a pen!) */
static void DrawFrame(HDC hdc, RECT rc, COLORREF col, int thick)
{
    HPEN p = CreatePen(PS_SOLID, thick, col);
    HPEN old = SelectObject(hdc, p);
    SetBkMode(hdc, TRANSPARENT);
    MoveToEx(hdc, rc.left,  rc.top,    NULL);
    LineTo(hdc,  rc.right,  rc.top);
    LineTo(hdc,  rc.right,  rc.bottom);
    LineTo(hdc,  rc.left,   rc.bottom);
    LineTo(hdc,  rc.left,   rc.top);
    SelectObject(hdc, old);
    DeleteObject(p);
}

static void DrawGradient(HDC hdc, RECT r, COLORREF c1, COLORREF c2)
{
    TRIVERTEX v[2]; GRADIENT_RECT gr;
    v[0].x = r.left;  v[0].y = r.top;
    v[0].Red = GetRValue(c1)*256; v[0].Green = GetGValue(c1)*256; v[0].Blue = GetBValue(c1)*256; v[0].Alpha = 0;
    v[1].x = r.right; v[1].y = r.bottom;
    v[1].Red = GetRValue(c2)*256; v[1].Green = GetGValue(c2)*256; v[1].Blue = GetBValue(c2)*256; v[1].Alpha = 0;
    gr.UpperLeft = 0; gr.LowerRight = 1;
    GradientFill(hdc, v, 2, &gr, 1, GRADIENT_FILL_RECT_V);
}

static void CenterText(HDC hdc, const wchar_t* s, int cx, int cy, COLORREF col, HFONT f)
{
    SIZE sz; SetTextColor(hdc, col); SelectObject(hdc, f);
    GetTextExtentPoint32W(hdc, s, (int)wcslen(s), &sz);
    TextOutW(hdc, cx - sz.cx/2, cy, s, (int)wcslen(s));
}

static void PaintScreen(HDC hdc)
{
    RECT rc = {0,0,WIN_W,WIN_H};
    int i, x, y;
    DrawGradient(hdc, rc, RGB(9,12,24), RGB(30,22,44));
    /* stars (deterministic) */
    for (i = 0; i < 60; i++) {
        x = (i*137 + 29) % WIN_W;
        y = (i*89  + 13) % (WIN_H/2);
        SetPixel(hdc, x, y, RGB(110,112,150));
    }

    switch (g_screen) {
    case SCR_LAUNCH:
        CenterText(hdc, S_LOGO,   WIN_W/2, 84,  RGB(235,225,190), g_fTitle);
        CenterText(hdc, S_SLOGAN, WIN_W/2, 156, RGB(170,160,190), g_fMed);
        CenterText(hdc, S_SUBT,   WIN_W/2, 434, RGB(110,110,130), g_fSmall);
        break;
    case SCR_SELECT:
        CenterText(hdc, H_SELECT, WIN_W/2, 14, RGB(235,225,190), g_fMed);
        break;
    case SCR_LORE:
        break;
    case SCR_READY: {
        wchar_t line[160];
        CenterText(hdc, H_READY1, WIN_W/2, 120, RGB(240,220,160), g_fBig);
        if (g_selected >= 0) {
            wsprintfW(line, L"%ls: %ls", H_READY2, g_class[g_selected].name);
            CenterText(hdc, line, WIN_W/2, 190, RGB(220,220,235), g_fMed);
            CenterText(hdc, H_READY3, WIN_W/2, 230, RGB(140,170,140), g_fSmall);
        }
        break; }
    }
}

